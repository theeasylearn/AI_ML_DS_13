a = 10
b = 3

print(f"a = {a} b = {b}")
# a = a + b
a+=b
print(f"after addition a = {a} b = {b}")

# a = a - b
a-=b
print(f"after subtraction a = {a} b = {b}")

# a = a * b
a *=b
print(f"after multiplication a = {a} b = {b}")

# a = a / b
a/=b
print(f"after division a = {a} b = {b}")

# a = a ** b
a**=b
print(f"after power a = {a} b = {b}")

# a = a % b
a%=b
print(f"after modulo a = {a} b = {b}")
