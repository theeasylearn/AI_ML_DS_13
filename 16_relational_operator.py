#example of relational operator

a = 10
b = 11

result = a == b 
print(f"{result} = {a} == {b}")

result = a != b 
print(f"{result} = {a} != {b}")


result = a < b 
print(f"{result} = {a} < {b}")

result = a > b 
print(f"{result} = {a} > {b}")

result = a <= b 
print(f"{result} = {a} != {b}")

result = a >= b 
print(f"{result} = {a} >= {b}")




